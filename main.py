def load_dataset(dataset_name, img_height, img_width, first_frame_num, num_frames, device):
    """
    Loads images from the DAVIS 2017 dataset format or similar structures.
    Converts RGB frames to grayscale and normalizes the tensor.
    """
    print(f"Generating Ground Truth images for sequence: {dataset_name}...")

    # Path adjusted for DAVIS 2017 structure: JPEGImages/Resolution/Sequence
    image_dir = os.path.join(dataset_name)

    if not os.path.exists(image_dir):
        raise FileNotFoundError(f"Directory not found: {image_dir}")

    image_paths = sorted(
        [os.path.join(image_dir, f) for f in os.listdir(image_dir)
         if f.lower().endswith((".png", ".jpg", ".jpeg"))]
    )
    print(len(image_paths))
    image_paths = image_paths[first_frame_num : first_frame_num + num_frames]

    if len(image_paths) == 0:
        raise ValueError("No images found in the specified range.")

    L_gt_list = []
    for path in image_paths:
        # DAVIS images are RGB; .convert("L") applies the ITU-R 601-2 luma transform:
        # L = R * 299/1000 + G * 587/1000 + B * 114/1000
        img_pil = Image.open(path).convert("L")
        img_resized = img_pil.resize((img_width, img_height), resample=Image.BILINEAR)
        img_np = np.array(img_resized).astype(np.float32)
        L_gt_list.append(torch.from_numpy(img_np))

    L_gt = torch.stack(L_gt_list) # Shape: (T, H, W)

    # Global normalization to [0, 1] range
    min_val = L_gt.min()
    max_val = L_gt.max()
    L_gt = (L_gt - min_val) / (max_val - min_val)

    #print(L_gt.shape)

    return L_gt.to(device)

"""# PSFエンジニアリング/PSF engineering

### 点拡がり関数（PSF）の作成/Create PSF
"""

def create_psf(img_height, img_width, num_delta, seed, device):
    """Generates the Point Spread Function (PSF)."""
    gen_psf = torch.Generator().manual_seed(seed)
    h_psf = torch.zeros(img_height, img_width)

    if num_delta == 1:
        # Identity mapping (center pixel)
        center_y = img_height // 2
        center_x = img_width // 2
        h_psf[center_y, center_x] = 1.0
    else:
        # Random k-points
        # 画像の全座標を生成
        coords = torch.cartesian_prod(torch.arange(img_height), torch.arange(img_width))
        # ランダムにnum_delta個の座標を選択
        selected_indices = coords[torch.randperm(len(coords), generator=gen_psf)[:num_delta]]
        # 選択された座標に1.0を配置
        for y, x in selected_indices:
            h_psf[y, x] = 1.0

    h_psf = h_psf.to(device)
    h_psf /= h_psf.sum() # Normalize
    return h_psf

"""### 撮影動画とPSFの畳み込み/Convolve sequence with PSF

$g = L * h$
"""

def convolve_sequence_with_psf(L_seq, psf):
    """
    Convolves the entire video sequence with the PSF using FFT.
    L_seq: (T, H, W) Tensor
    psf: (H, W) Kernel
    """
    T, H, W = L_seq.shape

    # Broadcast PSF to (T, H, W)
    # PSFは空間的に同じなので、FFTで一度計算すれば全フレームに適用できる
    h_shifted = torch.fft.fftshift(psf)
    H_fft = torch.fft.fft2(h_shifted, s=(H, W))

    # L_seqの各フレームに対してFFTを計算
    F_L = torch.fft.fft2(L_seq)        # (T, H, W)
    # PSFのFFTを全フレームに適用するためにブロードキャスト
    F_H = H_fft[None, :, :]            # Broadcast to (1, H, W)
    F_conv = F_L * F_H

    # 逆FFTで空間領域に戻す
    conv_result = torch.fft.ifft2(F_conv).real
    return conv_result

"""# 観測ノイズの付加/Add noise"""

def add_awgn(x, snr_db, seed=None):
    """Adds Additive White Gaussian Noise based on SNR."""
    if not np.isfinite(snr_db):
        return x

    sig_power = (x.float().pow(2).mean()).item()
    if sig_power <= 0:
        return x

    sig_power_db = 10.0 * np.log10(sig_power)
    noise_power_db = sig_power_db - snr_db
    noise_power = 10.0 ** (noise_power_db / 10.0)

    gen = torch.Generator().manual_seed(seed) if seed else None
    noise = torch.randn(x.shape, generator=gen) * np.sqrt(noise_power)
    noise = noise.to(x.device)

    return x + noise

"""# スパイクを計測/Detecting spikes"""

def generate_accum_map(g_seq, threshold):
    num_frames, height, width = g_seq.shape
    device = g_seq.device

    # 参照フレームの初期化
    g_ref_seq = torch.zeros_like(g_seq).to(device)
    g_ref_seq[0] = g_seq[0]
    g_ref = g_ref_seq[0].clone()

    accum_map = torch.zeros_like(g_seq).to(device)
    accum_map[0] = g_seq[0]
    accum_ref = g_seq[0].clone()

    for t in range(1, num_frames):
        current_accum_value = accum_ref + g_seq[t]
        accum_map[t] = current_accum_value.clone()

        # しきい値に基づいてスパイクの有無を決定
        s = torch.zeros_like(current_accum_value).to(device)
        s[current_accum_value >= threshold]  =  1.0

        accum_ref = current_accum_value.clone()
        accum_ref = torch.where(s == 1.0, accum_ref - threshold, accum_ref)

        # Update reference intensity: g_ref <- g_ref + theta * s
        g_ref = g_ref + threshold * s
        g_ref_seq[t] = g_ref

    return accum_map, g_ref_seq

def generate_events(accum_map, threshold):
    """Generates discrete event map (+1, 0, -1) from delta map."""
    device = accum_map.device
    sigma = torch.zeros_like(accum_map).to(device)
    sigma[accum_map >= threshold] = 1.0
    photon_sum = torch.sum(sigma, dim=0) * threshold
    return sigma, photon_sum

def accum_spike(sigma_gt, gt):
    spike_accum = torch.cumsum(sigma_gt, dim=0)
    photon_accum = torch.cumsum(gt, dim=0)

    return spike_accum, photon_accum

"""# TFW・TFI

### TFW
"""

def tfw(sigma_gt, w):
    spike_cumsum = torch.cumsum(sigma_gt, dim=0)

    tfw_sum = torch.zeros_like(sigma_gt)

    tfw_sum[w-1:] = spike_cumsum[w-1:]
    tfw_sum[w:] -= spike_cumsum[:-w]

    tfw_img = (tfw_sum / w) * radiance_threshold
    tfw_img = torch.clamp(tfw_img, max=1.0)
    return tfw_img

"""### TFI"""

def tfi(sigma_gt, radiance_threshold):
  tfi_img_ref = torch.zeros_like(sigma_gt).to(device)
  tfi_img_ref[0] = torch.ones_like(sigma_gt[0])
  for i in range(1, len(sigma_gt)):
    tfi_img_ref[i] = torch.where(sigma_gt[i - 1] == 1, 1, tfi_img_ref[i - 1] + 1)
  #print(tfi_img_ref)
  tfi_img = torch.zeros_like(sigma_gt).to(device)
  tfi_img[-1] = tfi_img_ref[-1]
  for j in range(len(sigma_gt) - 1, 0, -1):
    #print(j)
    tfi_img[j - 1] = torch.where(tfi_img_ref[j - 1] < tfi_img_ref[j], tfi_img[j], tfi_img_ref[j - 1])
  #print(tfi_img)
  tfi_img = 1 / tfi_img
  tfi_img = tfi_img * radiance_threshold
  tfi_img = torch.clamp(tfi_img, max=1.0)
  return tfi_img

"""# 損失関数/Loss Function"""

def hinge_loss_ver2(gt, sigma_gt, threshold, epsilon):
    """Calculates the Hinge-like event loss."""
    spike_accum, photon_accum = accum_spike(sigma_gt, gt)
    photon_sup = (spike_accum + 1) * threshold
    photon_inf = spike_accum * threshold

    over_loss = torch.clamp(photon_accum - photon_sup, min=0.0).sum()
    under_loss = torch.clamp(photon_inf - photon_accum, min=0.0).sum()

    return over_loss + under_loss

# 正則化項として、隣接ピクセル・フレーム間の滑らかさに関する条件を入れる
def total_variation_3d(x, x_weight, y_weight, t_weight, reduction='sum'):
    """Calculates Spatio-Temporal Total Variation."""
    if x.dim() != 3:
        raise ValueError("Input must be 3D tensor")

    T, H, W = x.shape
    eps = 1e-8

    # 時間、空間の差分を計算（最後のフレーム/行/列は0でパディング）
    dt = torch.cat([x[1:] - x[:-1], torch.zeros(1,H,W, device=x.device, dtype=x.dtype)], dim=0)
    dy = torch.cat([x[:,1:] - x[:,:-1], torch.zeros(T,1,W, device=x.device, dtype=x.dtype)], dim=1)
    dx = torch.cat([x[:,:,1:] - x[:,:,:-1], torch.zeros(T,H,1, device=x.device, dtype=x.dtype)], dim=2)
    tv = torch.sqrt(eps + t_weight*dt**2 + y_weight*dy**2 + x_weight*dx**2)
    return tv.sum()

"""# 最適化処理/Optimization

with PSF engineering, Hinge Loss ver2
"""

def run_optimization_ver2(seed_L_hat, num_frames, img_height, img_width, learning_rate, num_iterations, x_weight, y_weight, t_weight, lambda_tv, L_gt, h_psf, radiance_threshold, sigma_gt, photon_sum, margin):
    """Main Optimization Loop."""

    # 1. Initialize L_hat
    print("Initializing reconstruction...")
    gen_L_hat = torch.Generator().manual_seed(seed_L_hat)


    L_hat = torch.rand(num_frames, img_height, img_width, generator=gen_L_hat)
    L_hat /= L_hat.mean()
    L_hat = L_hat.to(device).detach().clone().requires_grad_(True)

    optimizer = torch.optim.AdamW([L_hat], lr=learning_rate)

    # 2. Loop
    print(f"Starting Adam optimization ({num_iterations} iterations)...")
    loss_history = []
    loss_spike_history = []
    loss_tv_history = []

    best_loss = float('inf')
    best_L_hat = None

    for iteration in tqdm(range(1, num_iterations + 1)):
        optimizer.zero_grad()

        # Forward
        g_hat = convolve_sequence_with_psf(L_hat, h_psf)

        # Loss
        l_event = hinge_loss_ver2(g_hat, sigma_gt, radiance_threshold, margin)
        l_tv = total_variation_3d(L_hat, x_weight, y_weight, t_weight, reduction='sum')
        loss = l_event + lambda_tv * l_tv

        loss.backward()
        optimizer.step()

        # Projection / Constraints
        with torch.no_grad():
            #L_hat.div_(L_hat.mean())
            L_hat.clamp_(min=0.0, max=1.0)
            #L_hat.div_(torch.sum(L_hat, dim=0) / photon_sum)

        # Logging
        loss_val = loss.item()
        loss_history.append(loss_val)
        loss_spike_history.append(l_event.item())
        loss_tv_history.append(l_tv.item())

        if loss_val < best_loss:
            best_loss = loss_val
            best_L_hat = L_hat.detach().clone()

        if iteration % (num_iterations // 10) == 0:
            tqdm.write(f"Iter {iteration}: Loss={loss_val:.6f} (Ev={l_event.item():.6f}, TV={l_tv.item():.6f})")

    print("Optimization Complete.")
    return best_L_hat, loss_history, loss_spike_history, loss_tv_history, best_loss

"""# 評価指標 / Evaluation

## PSNRの計算/Calculation of PSNR
"""

def psnr(gt, pred):
    mse = torch.mean((gt - pred) ** 2)
    if mse == 0:
        return float('inf')
    max_pixel = 1.0
    return 20 * torch.log10(max_pixel / torch.sqrt(mse))

"""## SSIMの計算/Calculation of SSIM"""

def ssim_video(gt, pred, data_range=1.0):
    gt_np = gt.detach().cpu().numpy()
    pred_np = pred.detach().cpu().numpy()

    ssim_list = []
    for t in range(gt_np.shape[0]):
        score = ssim(
            gt_np[t],
            pred_np[t],
            data_range=data_range
        )
        ssim_list.append(score)

    return np.mean(ssim_list)

