def hooke_jeeves_opt(f, x0, alpha, epsilon, gamma=0.5):
    x = np.array(x0, dtype=float)
    y, _ = f(x, sigma_gt_g, photon_sum_g)
    n = len(x)
    iter = 1

    while alpha > epsilon and iter <= 12:
        improved = False
        x_best, y_best = x.copy(), y

        for i in range(n):
            for sgn in [-1, 1]:
                x_phi = x.copy()

                x_phi[i] += sgn * alpha * x[i]

                y_phi, z_phi = f(x_phi, sigma_gt_g, photon_sum_g)

                if y_phi < y_best:
                    x_best, y_best, z_best = x_phi, y_phi, z_phi
                    improved = True

        x, y, z = x_best, y_best, z_best
        if not improved:
            alpha *= gamma
            print(f"Step size reduced: alpha={alpha}")
            print(f"Current PSNR={-y}")

        if improved:
            print(f"Current learning rate={x[0]}")
            print(f"Current lambda tv={x[1]}")
            print(f"Current t_weight={x[2]}")
            print(f"Current PSNR={-y}")
        iter += 1
    return x

